"""
measure_roboto.py -- measures Roboto Regular's advance width for printable ASCII.

@kosmos-system  Content (KosmosWorlds) -- Mission Control (DB-043)
@kosmos-owner   Content lane

World text is Roboto (KWorldTextPool: RobotoDistanceField) and always centred
on its anchor. The bridge fakes left alignment by shifting each line by half its
width, so it needs real widths, not guesses. For each character c this lays out
"|" + c*40 + "|" and "||" at 1 em and takes the difference / 40: the advance in em.

    blender -b -P mission-control/blender/measure_roboto.py

Writes agent-bridge/src/roboto-advance.ts (generated; do not edit).
"""

import os

import bpy

FONT = "E:/Epic Games/UE_5.7/Engine/Content/Slate/Fonts/Roboto-Regular.ttf"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "agent-bridge", "src", "roboto-advance.ts")
N = 40

bpy.ops.wm.read_factory_settings(use_empty=True)
font = bpy.data.fonts.load(FONT)


def width(text):
    cu = bpy.data.curves.new("m", type="FONT")
    cu.body = text
    cu.font = font
    cu.size = 1.0
    o = bpy.data.objects.new("m", cu)
    bpy.context.collection.objects.link(o)
    bpy.context.view_layer.update()
    w = o.dimensions.x
    bpy.data.objects.remove(o, do_unlink=True)
    bpy.data.curves.remove(cu)
    return w


base = width("||")
adv = []
for code in range(32, 127):
    c = chr(code)
    adv.append(round((width("|" + c * N + "|") - base) / N, 4))

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by KosmosWorlds mission-control/blender/measure_roboto.py from Roboto-Regular.ttf. Do not edit.\n")
    f.write("// Advance width in em of each printable ASCII character, from \" \" (32) to \"~\" (126).\n")
    f.write("export const ROBOTO_ADVANCE_EM: readonly number[] = [\n")
    for i in range(0, len(adv), 12):
        f.write("  " + ", ".join(str(a) for a in adv[i:i + 12]) + ",\n")
    f.write("];\n")
print("[measure_roboto] wrote", OUT, "space", adv[0], "M", adv[ord("M") - 32], "i", adv[ord("i") - 32])
