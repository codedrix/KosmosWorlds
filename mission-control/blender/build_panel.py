def group(n):
    """src/lib.rs group_by_name."""
    if n in FIXTURES:
        return "fixture"
    if n.startswith("SealRing") or n.startswith("TxSeal") or n in ("BtnSealType", "McSealCancel"):
        return "seal"
    if n in ("McLedge", "McClose") or n.startswith("Cube") or n.startswith("TxCube"):
        return "ledge"
    if n.startswith("Puck") or n.startswith("BtnPuck") or n == "TxPuck":
        return "puck"
    return "arc"


def parse_snapshot(path):
    recs = []
    for line in open(path, encoding="utf-8").read().split("\n"):
        if not line or line == "AB1":
            continue
        recs.append(line.split(" ", 2))
    return recs


def unescape(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            out.append("\n" if s[i + 1] == "n" else s[i + 1])
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


