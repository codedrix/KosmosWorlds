import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  ARC_TEXT_NODES,
  BUTTON_NODES,
  HUE_NODES,
  SHOW_NODES,
  TEXT_NODES,
  WORLD_ONLY_NODES,
  W,
  CONV_LEFT_M,
  hueVariant,
} from "../src/faces/mission-control/layout.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const nodesFile = path.resolve(here, "..", "..", "..", "mission-control", "nodes.json");

test("the world's nodes.json is the face's layout, name for name, in order", () => {
  const j = JSON.parse(fs.readFileSync(nodesFile, "utf8"));
  assert.deepEqual(Object.keys(j), ["$note", "text", "buttons", "show", "hue", "world"], "same keys, same order");
  assert.deepEqual(j.text, [...TEXT_NODES]);
  assert.deepEqual(j.buttons, [...BUTTON_NODES]);
  assert.deepEqual(j.show, [...SHOW_NODES]);
  assert.deepEqual(j.hue, Object.fromEntries(Object.entries(HUE_NODES).map(([k, v]) => [k, [...v]])));
  assert.deepEqual(Object.keys(j.hue), Object.keys(HUE_NODES), "the hue section's key order");
  assert.deepEqual(j.world, [...WORLD_ONLY_NODES]);
});

test("the generator writes nodes.json byte for byte (scripts/write-nodes-json.mjs)", () => {
  const body = {
    $note: "GENERATED by agent-bridge/scripts/write-nodes-json.mjs from src/faces/mission-control/layout.ts. Do not edit.",
    text: TEXT_NODES,
    buttons: BUTTON_NODES,
    show: SHOW_NODES,
    hue: HUE_NODES,
    world: WORLD_ONLY_NODES,
  };
  const want = JSON.stringify(body, null, 2) + "\n";
  const got = fs.readFileSync(nodesFile, "utf8").replace(/\r\n/g, "\n");
  assert.equal(got, want);
});

test("every hue state has its variant node in `world`, named <base><State>", () => {
  assert.deepEqual(HUE_NODES.CubeA, ["calm", "need", "idle"]);
  assert.deepEqual(HUE_NODES.Puck, ["calm", "need"]);
  assert.deepEqual(HUE_NODES.SealRing, ["armed", "locked"]);
  const world = new Set<string>(WORLD_ONLY_NODES);
  for (const [base, states] of Object.entries(HUE_NODES)) {
    for (const st of states) assert.ok(world.has(hueVariant(base, st)), `${hueVariant(base, st)} is in world`);
  }
  assert.equal(hueVariant("CubeA", "need"), "CubeANeed");
  assert.equal(hueVariant("SealRing", "locked"), "SealRingLocked");
  for (const n of ["CubeANeed", "CubeDIdle", "PuckCalm", "PuckNeed", "SealRingArmed", "SealRingLocked"]) assert.ok(world.has(n), n);
});

test("node names follow the device rules", () => {
  const all = [...TEXT_NODES, ...BUTTON_NODES, ...SHOW_NODES, ...WORLD_ONLY_NODES];
  assert.equal(new Set(all).size, all.length, "no duplicates");
  for (const n of all) {
    // The client strips a trailing _<digit>; k_node_find wants plain names.
    assert.match(n, /^[A-Z][A-Za-z]{1,30}$/, n);
  }
  assert.equal(TEXT_NODES.length, 31);
  assert.ok(ARC_TEXT_NODES.length + 4 + 1 <= 29, "the arc state shows at most 29 labels (arc + four cubes + the puck)");
});

test("the line widths are the contract's (narrowed for the v2.1 panels, section 8)", () => {
  assert.deepEqual({ ...W }, {
    ticker: 0.78, status: 1.2, project: 0.85, rail: 0.74, done: 0.78,
    header: 1.2, conv: 1.2, ask: 1.1, pageSpot: 0.72, cube: 0.34, puck: 0.8, seal: 0.45, sealHint: 1.0, watch: 0.5,
  });
  assert.equal(CONV_LEFT_M, -0.6);
});
