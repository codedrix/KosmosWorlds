// Writes ../mission-control/nodes.json from the face's layout (run after `npm run build`).
// The Blender script builds these nodes, the world script finds them, and
// test/layout.test.ts fails if the file and the layout drift apart.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TEXT_NODES, BUTTON_NODES, SHOW_NODES, HUE_NODES, WORLD_ONLY_NODES } from "../dist/src/faces/mission-control/layout.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "..", "..", "mission-control", "nodes.json");
const body = {
  $note: "GENERATED by agent-bridge/scripts/write-nodes-json.mjs from src/faces/mission-control/layout.ts. Do not edit.",
  text: TEXT_NODES,
  buttons: BUTTON_NODES,
  show: SHOW_NODES,
  hue: HUE_NODES,
  world: WORLD_ONLY_NODES,
};
fs.writeFileSync(out, JSON.stringify(body, null, 2) + "\n");
console.log(`wrote ${out}: ${TEXT_NODES.length} text, ${BUTTON_NODES.length} buttons, ${SHOW_NODES.length} show, ${Object.keys(HUE_NODES).length} hue, ${WORLD_ONLY_NODES.length} world-only`);
