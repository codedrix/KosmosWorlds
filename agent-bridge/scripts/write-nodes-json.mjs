// Writes ../mission-control/nodes.json from the faces' layouts (run after `npm run build`):
// Mission Control's (src/faces/mission-control/layout.ts) and the Kosmos Desk board's
// (src/faces/desk/layout.ts: the `desk_text` and `desk_world` keys).
// The Blender script builds Mission Control's nodes, lobby/make_desk_glb.mjs builds the board's,
// the world script finds them all, and test/layout.test.ts fails if the file and the layouts drift apart.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TEXT_NODES, BUTTON_NODES, SHOW_NODES, HUE_NODES, WORLD_ONLY_NODES } from "../dist/src/faces/mission-control/layout.js";
import { DESK_TEXT_NODES, DESK_WORLD_NODES } from "../dist/src/faces/desk/layout.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "..", "..", "mission-control", "nodes.json");
const body = {
  $note: "GENERATED by agent-bridge/scripts/write-nodes-json.mjs from src/faces/mission-control/layout.ts and src/faces/desk/layout.ts. Do not edit.",
  text: TEXT_NODES,
  buttons: BUTTON_NODES,
  show: SHOW_NODES,
  hue: HUE_NODES,
  world: WORLD_ONLY_NODES,
  desk_text: DESK_TEXT_NODES,
  desk_world: DESK_WORLD_NODES,
};
fs.writeFileSync(out, JSON.stringify(body, null, 2) + "\n");
console.log(
  `wrote ${out}: ${TEXT_NODES.length} text, ${BUTTON_NODES.length} buttons, ${SHOW_NODES.length} show, ${Object.keys(HUE_NODES).length} hue, ` +
    `${WORLD_ONLY_NODES.length} world-only, ${DESK_TEXT_NODES.length} desk text, ${DESK_WORLD_NODES.length} desk world`,
);
